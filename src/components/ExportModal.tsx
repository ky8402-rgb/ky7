import React, { useState } from 'react';
import { 
  NicheItem, 
  ChannelBranding, 
  ContentPlan, 
  VideoScript, 
  ThumbnailData, 
  SeoData 
} from '../types';
import { X, Copy, Check, Download, FileText } from 'lucide-react';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  niche: NicheItem;
  branding: ChannelBranding;
  contentPlan: ContentPlan;
  script: VideoScript;
  thumbnail: ThumbnailData;
  seo: SeoData;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  niche,
  branding,
  contentPlan,
  script,
  thumbnail,
  seo,
}) => {
  const [copied, setCopied] = useState<boolean>(false);

  if (!isOpen) return null;

  const selectedName = branding.channelNames[branding.selectedNameIndex] || branding.channelNames[0];

  const generateMarkdown = () => {
    return `# 🎬 YouTube Channel Master Launch Blueprint
Generated by ChannelForge AI Studio

---

## 1. NICHE VIABILITY & AUDIENCE
- **Channel Niche:** ${niche.name} (${niche.category})
- **Strategic Verdict:** ${niche.strategicVerdict}
- **Estimated CPM:** $${niche.estimatedCPM.toFixed(2)} / 1,000 views
- **Demand Score:** ${niche.demandScore}/100 | **Viral Score:** ${niche.viralScore}/100
- **Zero Budget Strategy:** ${niche.bestForZeroBudgetReason}
- **Free Tech Stack:** ${niche.recommendedTools.join(', ')}
- **Monetization Engines:** ${niche.monetizationMethods.join(', ')}

---

## 2. BUILD MY CHANNEL FROM SCRATCH (BRANDING & SETUP)
- **Channel Name:** ${selectedName.name}
- **YouTube Handle:** ${selectedName.handle}
- **Tagline:** "${branding.tagline}"
- **Value Proposition:** ${branding.valueProposition}

### SEO-Friendly Channel Description ("About" Bio):
\`\`\`
${branding.aboutBio}
\`\`\`

### Channel Keywords (YouTube Studio Settings):
\`${(branding.channelKeywords || []).join(', ')}\`

### Branding Ideas to Stand Out From Competitors:
${(branding.brandingIdeas || []).map(idea => `- **${idea.title} (${idea.category}):** ${idea.description}`).join('\n')}

### Complete Channel Setup Checklist:
${(branding.setupChecklist || []).map(item => `- [${item.completed ? 'x' : ' '}] **[${item.category}] ${item.task}** — ${item.whyItMatters}`).join('\n')}

### Visual Aesthetic & Safe Zone Specs:
- **Color Palette:** Primary ${branding.colorPalette.primary} | Accent ${branding.colorPalette.accent} | Card ${branding.colorPalette.card}
- **Mood:** ${branding.colorPalette.mood}
- **Banner Headline:** "${branding.bannerConcept.headlineText}"
- **Banner Subtext:** "${branding.bannerConcept.subText}"
- **Banner Badge:** "${branding.bannerConcept.uploadBadgeText}"
- **Banner Visual Prompt (Midjourney/Leonardo):**
> ${branding.bannerConcept.visualDescription}

---

## 3. 30 HIGH-POTENTIAL VIRAL VIDEO IDEAS
**Strategy:** ${contentPlan.strategy}
**Target Audience ([AUDIENCE]):** ${contentPlan.targetAudience}

${contentPlan.weeks.map(week => `
### Week ${week.weekNumber}: ${week.phase}
${week.videos.map((v, idx) => `- **Idea #${v.ideaNumber ?? idx + 1}: [${v.format} - ${v.targetDuration}] ${v.title}** (${v.viralDriver || 'High Audience Demand'} | Shareability: ${v.shareabilityScore ?? 95}/100)
  - **Opening Hook:** "${v.hook}"
  - **Video Concept:** ${v.concept || 'High-retention psychological narrative.'}
  - **Thumbnail Idea:** ${v.thumbnailConcept}
  - **Upload Day:** ${v.uploadDay} | **Est. CTR:** ${v.predictedCTR}
`).join('')}
`).join('\n')}

---

## 4. LAUNCH VIDEO SCRIPT: "${script.title}"
- **Target Duration:** ${script.estimatedDuration}
- **Predicted Retention:** ${script.predictedRetention}
- **Hook Strategy:** ${script.hookStrategy}
- **Recommended Pace:** ${script.ttsNarrationSpeed}

### Timeline Script Breakdown:
${script.sections.map(s => `
#### [${s.timestamp}] ${s.sectionName} (${s.durationSeconds}s)
- **Visual B-Roll:** ${s.visualCue}
- **SFX:** ${s.soundFX}
- **Pattern Interrupt:** ${s.patternInterruptNote}
- **Voiceover Narration:**
  > "${s.voiceover}"
`).join('\n')}

---

## 5. HIGH-CTR THUMBNAIL BLUEPRINT
- **Concept Name:** ${thumbnail.conceptName}
- **Bold Headline:** "${thumbnail.boldHeadline}"
- **Headline Color:** ${thumbnail.headlineColor}
- **Focal Element:** ${thumbnail.focalElement}
- **Midjourney / Flux Generation Prompt:**
> ${thumbnail.midjourneyPrompt}

---

## 6. VIDEO SEO & PUBLISHING KIT
- **Title Option A:** ${seo.titleA}
- **Title Option B:** ${seo.titleB}
- **Title Option C:** ${seo.titleC}

### Description:
\`\`\`
${seo.description}
\`\`\`

### Tags:
${seo.tags.join(', ')}

### Pinned Comment:
"${seo.pinnedComment}"

### Hashtags:
${seo.hashtags.join(' ')}

---

## 7. 0 TO 10,000 SUBSCRIBERS MILESTONE SUMMARY
1. **Phase 1 (Days 1-14):** 3 Long-form benchmark videos + 5 YouTube Shorts feeders.
2. **Phase 2 (Days 15-45):** 2 Long-form weekly + 2 Shorts. Eliminate 0:00-0:30 friction for 4,000 watch hours.
3. **Phase 3 (Days 45-75):** Apply for YPP; deploy affiliate links in top 3 lines of description.
4. **Phase 4 (Days 75-120):** Launch $19-$39 proprietary digital product; pitch sponsors with rate card.
`;
  };

  const markdownContent = generateMarkdown();

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${selectedName.name.replace(/\s+/g, '_')}_YouTube_Channel_Blueprint.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fade-in">
      <div 
        className="w-full max-w-4xl bg-zinc-950 border border-zinc-800 rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[90vh]"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="p-4 sm:p-5 bg-zinc-900 border-b border-zinc-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-red-500" />
            <div>
              <h3 className="font-extrabold text-white text-base">
                Export Master YouTube Channel Blueprint
              </h3>
              <p className="text-xs text-zinc-400">Complete plan ready to save, print, or share</p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-3 py-1.5 rounded-lg bg-zinc-800 hover:bg-zinc-700 text-zinc-200 text-xs font-semibold flex items-center gap-1.5 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Markdown'}</span>
            </button>

            <button
              onClick={handleDownload}
              className="px-3.5 py-1.5 rounded-lg bg-red-600 hover:bg-red-500 text-white text-xs font-semibold flex items-center gap-1.5 transition-colors shadow-md"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>

            <button
              onClick={onClose}
              className="p-1 rounded-lg text-zinc-400 hover:text-white hover:bg-zinc-800 transition-colors ml-1"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Content Preview */}
        <div className="p-5 sm:p-6 overflow-y-auto">
          <pre className="p-4 rounded-xl bg-zinc-900 border border-zinc-800 text-zinc-300 font-mono text-xs leading-relaxed whitespace-pre-wrap select-all">
            {markdownContent}
          </pre>
        </div>

        {/* Footer */}
        <div className="p-4 bg-zinc-900 border-t border-zinc-800 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-zinc-800 hover:bg-zinc-700 text-white text-xs font-semibold transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
